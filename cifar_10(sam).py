class BasicBlock(nn.Module):
  def __init__(self, in_channels, out_channels, stride=1):
    super().__init__()

    self.conv1 = nn.Conv2d(in_channels, out_channels, 3, stride, 1, bias=False)
    self.bn1 = nn.BatchNorm2d(out_channels)
    self.relu = nn.ReLU()

    self.conv2 = nn.Conv2d(out_channels, out_channels, 3, 1, 1, bias=False)
    self.bn2 = nn.BatchNorm2d(out_channels)

    self.shortcut = nn.Sequential()

    if in_channels != out_channels or stride != 1:
      self.shortcut = nn.Sequential(
        nn.Conv2d(in_channels, out_channels, 1, stride, bias=False),
        nn.BatchNorm2d(out_channels)
      )

  def forward(self, x):
    identity = self.shortcut(x)

    x = self.conv1(x)
    x = self.bn1(x)
    x = self.relu(x)

    x = self.conv2(x)
    x = self.bn2(x)
    x += identity
    x = self.relu(x)

    return x

class ResNet(nn.Module):
  def __init__(self, block, num_blocks_arr, num_classes=10):
    super().__init__()
    self.conv1 = nn.Sequential(
        nn.Conv2d(3, 16, 3, 1, 1, bias=False),
        nn.BatchNorm2d(16),
        nn.ReLU()
    )
    self.in_channels = 16
    self.conv2 = self._make_layer(block, 16, num_blocks_arr[0], 1)
    self.conv3 = self._make_layer(block, 32, num_blocks_arr[1], 2)
    self.conv4 = self._make_layer(block, 64, num_blocks_arr[2], 2)
    # self.avgpool = nn.AvgPool2d(8)
    self.avgpool = nn.AdaptiveAvgPool2d((1,1))
    self.flatten = nn.Flatten()
    # self.fc = nn.Linear(8*8*64, num_classes)
    self.fc = nn.Linear(64, num_classes)

    self._init_layer()

  def _make_layer(self, block, out_channels, num_blocks, stride=1):
    strides = [stride] + [1] * (num_blocks-1)
    layers = []
    for stride in strides:
      layers.append(BasicBlock(self.in_channels, out_channels, stride))
      self.in_channels = out_channels
    return nn.Sequential(*layers)


  def _init_layer(self):
    for m in self.modules():
      if isinstance(m, nn.Conv2d):
        nn.init.kaiming_normal_(m.weight, mode='fan_out', nonlinearity='relu')
      elif isinstance(m, (nn.BatchNorm2d, nn.GroupNorm)):
        nn.init.constant_(m.weight, 1)
        nn.init.constant_(m.bias, 0)


  def forward(self, x):
    x = self.conv1(x)
    x = self.conv2(x)
    x = self.conv3(x)
    x = self.conv4(x)

    x = self.avgpool(x)
    x = self.flatten(x)
    x = self.fc(x)

    return x

